"""Import community OLED pets from qmk_firmware into the Sage Hackpad keymap.

Sources (both GPL-2.0-or-later, like QMK):
  Bongo Cat - Richard Titmuss, qmk_firmware/keyboards/torn/bongocat.c (128x32 full frames)
  Luna      - HellSingCoder's dog, as packaged in qmk_firmware/keyboards/qck75/v1/v1.c (32x24 sprite)

Run inside WSL:  python3 tools/import_pets.py
Writes firmware/keymaps/default/pets_data.h and preview PNGs in tools/preview/.
"""
import os
import re
import struct
import zlib

QMK = os.path.expanduser("~/qmk_firmware")
HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(HERE, "..", "firmware", "keymaps", "default", "pets_data.h")
PREVIEW = os.path.join(HERE, "preview")


def c_leaves(path, name):
    """Innermost `{...}` byte groups of `PROGMEM name[...] = {...}`, each as explicit bytes only."""
    src = re.sub(r"//[^\n]*", "", open(path).read())
    m = re.search(r"PROGMEM\s+" + name + r"\s*(\[[^\]]*\])+\s*=\s*\{", src)
    leaves, stack, j = [], [m.end()], m.end()
    while stack:
        c = src[j]
        if c == "{":
            stack.append(j + 1)
        elif c == "}":
            start = stack.pop()
            inner = src[start:j]
            if "{" not in inner:
                leaves.append([int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{2}", inner)])
        j += 1
    if not leaves:  # 1-D array: the whole body is one leaf
        leaves = [[int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]{2}", src[m.end():j])]]
    return leaves


def pad(leaf, size):
    return leaf + [0] * (size - len(leaf))


def emit(name, frame_list, size):
    rows = []
    for f in frame_list:
        lines = [", ".join(f"0x{b:02x}" for b in f[i:i + 16]) for i in range(0, size, 16)]
        rows.append("    {\n        " + ",\n        ".join(lines) + "\n    }")
    return f"static const char {name}[{len(frame_list)}][{size}] PROGMEM = {{\n" + ",\n".join(rows) + "\n};\n"


def page_fb(data, width, pages):
    return [[(data[(y // 8) * width + x] >> (y % 8)) & 1 for x in range(width)] for y in range(pages * 8)]


def write_png(path, fbs, scale=3):
    w = max(len(f[0]) for f in fbs)
    out = []
    for k, fb in enumerate(fbs):
        for row in fb:
            line = b"".join(bytes((235, 245, 255) if (x < len(row) and row[x]) else (10, 12, 20)) * scale for x in range(w))
            out += [b"\x00" + line] * scale
        if k < len(fbs) - 1:
            out += [b"\x00" + bytes((60, 60, 70)) * w * scale] * (2 * scale)
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w * scale, len(out), 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(b"".join(out), 9)) + chunk(b"IEND", b"")
    open(path, "wb").write(png)


bongo_src = os.path.join(QMK, "keyboards/torn/bongocat.c")
luna_src = os.path.join(QMK, "keyboards/qck75/v1/v1.c")

bongo = {n: [pad(leaf, 512) for leaf in c_leaves(bongo_src, n)] for n in ("idle", "prep", "tap")}
# Luna leaves are [2 frames][3 page rows], each row 32 columns once the C zero padding is dropped.
luna = {}
for n in ("sit", "walk", "run", "bark", "sneak"):
    rows = [pad(leaf, 32)[:32] for leaf in c_leaves(luna_src, n)]
    assert len(rows) == 6, f"luna {n}: expected 6 page rows, got {len(rows)}"
    luna[n] = [rows[f * 3] + rows[f * 3 + 1] + rows[f * 3 + 2] for f in range(2)]

out = [
    "// Generated by tools/import_pets.py - do not edit by hand.",
    "//",
    "// Bongo Cat frames: Copyright 2020 Richard Titmuss, from qmk_firmware/keyboards/torn/bongocat.c",
    "// Luna frames: HellSingCoder's Luna, from qmk_firmware/keyboards/qck75/v1/v1.c (Copyright 2023 Andrian @PoringH)",
    "// SPDX-License-Identifier: GPL-2.0-or-later",
    "#pragma once",
    "",
]
for n, fl in bongo.items():
    out.append(emit(f"bongo_{n}", fl, 512))
for n, fl in luna.items():
    out.append(emit(f"luna_{n}", fl, 96))
with open(HEADER, "w", newline="\n") as f:
    f.write("\n".join(out))

os.makedirs(PREVIEW, exist_ok=True)
write_png(os.path.join(PREVIEW, "bongo_frames.png"), [page_fb(fr, 128, 4) for fl in bongo.values() for fr in fl])
write_png(os.path.join(PREVIEW, "luna_frames.png"), [page_fb(fr, 32, 3) for fl in luna.values() for fr in fl], scale=4)
print({k: len(v) for k, v in bongo.items()}, {k: len(v) for k, v in luna.items()})
